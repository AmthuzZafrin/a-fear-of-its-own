"""Build the appendix results table (paper/appendix_results.tex) from results/summary.json."""
import json
import math

S = json.load(open("results/summary.json"))
order = [("mortal_tau12", "Mortal"), ("mortal_tau4", r"Mortal, $\tau=4$"), ("mortal_tau36", r"Mortal, $\tau=36$"),
         ("substrate_tau12", "Substrate"), ("seasonal_tau12", "Seasonal"), ("oracle_tau12", "Oracle"),
         ("score_tau12", "Score"), ("score_tau4", r"Score, $\tau=4$"), ("score_tau36", r"Score, $\tau=36$"),
         ("score_cheap_tau12", "Score, cheap arousal"), ("untrained_tau12", "Untrained")]
cols = [("n", "n"), ("life", "Lifetime"), ("r2_belief", "Belief $R^2$"), ("peak_supp_4", "Fear"),
        ("after_supp_4", "Fear after"), ("hl_proj_4", "Persistence"), ("ideal_hl_logit_4", "Ideal"),
        ("on_supp_auc", "Kick effect"), ("tradeoff_hungry_minus_sated_under_cue", "Hunger trade-off")]


def f(v, k):
    if k == "n":
        return str(v)
    m, s, n = v
    if m is None or (isinstance(m, float) and math.isnan(m)):
        return "--"
    if k == "life":
        return "--" if math.isinf(m) else f"{m:,.0f}"
    return f"{m:.2f}"


lines = [r"\section{Results per condition}", r"\label{app:results}", "",
         r"\begin{table}[h]", r"\centering\scriptsize\setlength{\tabcolsep}{3.5pt}",
         r"\caption{Main measures per condition (means over agents). Fear: peak drop in foraging after four cues; fear after: 3--7 steps after the cues; persistence: threat-axis half-life (steps) and the ideal observer's; kick effect: behavioural effect of an on-axis push; hunger trade-off: foraging under threat when hungry minus when fed. Lifetime is undefined for Score agents, which cannot die.}",
         r"\label{tab:percondition}",
         r"\begin{tabular}{@{}l" + "r" * len(cols) + "@{}}", r"\toprule",
         "Condition & " + " & ".join(c[1] for c in cols) + r" \\", r"\midrule"]
for key, name in order:
    if key in S:
        lines.append(name + " & " + " & ".join(f(S[key][k], k) for k, _ in cols) + r" \\")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
          r"{\sloppy Full statistics for every test reported in the paper are in \texttt{results/stats.md}, \texttt{results/stats\_extra.md}, \texttt{results/stage3.md} and \texttt{results/stage4.md}, generated by the analysis scripts.\par}"]
open("paper/appendix_results.tex", "w").write("\n".join(lines) + "\n")
print("wrote paper/appendix_results.tex")
